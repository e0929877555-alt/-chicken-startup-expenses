-- 在 Supabase SQL Editor 執行此檔。
create table if not exists public.startup_expenses (
  id bigint generated by default as identity primary key,
  expense_date date not null,
  category text not null,
  item text not null,
  amount numeric(12,0) not null check (amount > 0),
  payer text not null default '店用帳戶',
  payment_status text not null default '已付款',
  receipt_status text not null default '有收據／發票',
  note text not null default '',
  created_at timestamptz not null default now()
);

alter table public.startup_expenses enable row level security;

-- 股東查看頁：允許匿名讀取費用清單。不要把 service role key 放在前端。
drop policy if exists "public can read startup expenses" on public.startup_expenses;
create policy "public can read startup expenses"
on public.startup_expenses for select
to anon, authenticated
using (true);

-- 不建立 anon insert/update/delete policy。
-- 新增資料必須走 Vercel /api/expenses，使用伺服器端寫入碼與 service role key。
-- 如需即時更新，Supabase Dashboard > Database > Replication 啟用 startup_expenses 的 Realtime。
grant select on public.startup_expenses to anon, authenticated;